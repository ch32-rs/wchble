/// `RCON[0]` is unused; key expansion reads `RCON[1..=10]`.
const RCON: [u8; 11] = [
    0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36,
];

/// AES-128 with an expanded key schedule.
#[derive(Clone)]
pub struct Aes128 {
    round_keys: [[u8; 16]; 11],
}

impl core::fmt::Debug for Aes128 {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("Aes128(<key schedule redacted>)")
    }
}

impl Aes128 {
    #[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
    pub fn new(key: &[u8; 16]) -> Self {
        let mut w = [[0u8; 4]; 44];
        for (i, word) in w.iter_mut().take(4).enumerate() {
            word.copy_from_slice(&key[4 * i..4 * i + 4]);
        }
        for i in 4..44 {
            let mut t = w[i - 1];
            if i % 4 == 0 {
                t = [t[1], t[2], t[3], t[0]];
                for b in &mut t {
                    *b = SBOX[*b as usize];
                }
                t[0] ^= RCON[i / 4];
            }
            for j in 0..4 {
                w[i][j] = w[i - 4][j] ^ t[j];
            }
        }

        let mut round_keys = [[0u8; 16]; 11];
        for (r, rk) in round_keys.iter_mut().enumerate() {
            for c in 0..4 {
                rk[4 * c..4 * c + 4].copy_from_slice(&w[4 * r + c]);
            }
        }
        Self { round_keys }
    }

    #[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
    pub fn encrypt_block(&self, block: &mut [u8; 16]) {
        add_round_key(block, &self.round_keys[0]);
        for rk in &self.round_keys[1..10] {
            sub_bytes(block);
            shift_rows(block);
            mix_columns(block);
            add_round_key(block, rk);
        }
        sub_bytes(block);
        shift_rows(block);
        add_round_key(block, &self.round_keys[10]);
    }

    #[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
    pub fn decrypt_block(&self, block: &mut [u8; 16]) {
        add_round_key(block, &self.round_keys[10]);
        for rk in self.round_keys[1..10].iter().rev() {
            inv_shift_rows(block);
            inv_sub_bytes(block);
            add_round_key(block, rk);
            inv_mix_columns(block);
        }
        inv_shift_rows(block);
        inv_sub_bytes(block);
        add_round_key(block, &self.round_keys[0]);
    }
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn add_round_key(s: &mut [u8; 16], rk: &[u8; 16]) {
    for i in 0..16 {
        s[i] ^= rk[i];
    }
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn sub_bytes(s: &mut [u8; 16]) {
    for b in s {
        *b = SBOX[*b as usize];
    }
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn inv_sub_bytes(s: &mut [u8; 16]) {
    for b in s {
        *b = INV_SBOX[*b as usize];
    }
}

/// State is column-major: `s[4 * column + row]`.
#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn shift_rows(s: &mut [u8; 16]) {
    for row in 0..4 {
        let a = [s[row], s[row + 4], s[row + 8], s[row + 12]];
        for col in 0..4 {
            s[4 * col + row] = a[(col + row) % 4];
        }
    }
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn inv_shift_rows(s: &mut [u8; 16]) {
    for row in 0..4 {
        let a = [s[row], s[row + 4], s[row + 8], s[row + 12]];
        for col in 0..4 {
            s[4 * col + row] = a[(col + 4 - row) % 4];
        }
    }
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn xtime(x: u8) -> u8 {
    (x << 1) ^ (((x >> 7) & 1) * 0x1b)
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn gmul(mut a: u8, mut b: u8) -> u8 {
    let mut r = 0u8;
    while b != 0 {
        if b & 1 != 0 {
            r ^= a;
        }
        a = xtime(a);
        b >>= 1;
    }
    r
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = 4 * c;
        let a = [s[i], s[i + 1], s[i + 2], s[i + 3]];
        s[i] = xtime(a[0]) ^ (xtime(a[1]) ^ a[1]) ^ a[2] ^ a[3];
        s[i + 1] = a[0] ^ xtime(a[1]) ^ (xtime(a[2]) ^ a[2]) ^ a[3];
        s[i + 2] = a[0] ^ a[1] ^ xtime(a[2]) ^ (xtime(a[3]) ^ a[3]);
        s[i + 3] = (xtime(a[0]) ^ a[0]) ^ a[1] ^ a[2] ^ xtime(a[3]);
    }
}

#[cfg_attr(target_arch = "riscv32", link_section = ".highcode")]
fn inv_mix_columns(s: &mut [u8; 16]) {
    for c in 0..4 {
        let i = 4 * c;
        let a = [s[i], s[i + 1], s[i + 2], s[i + 3]];
        s[i] = gmul(a[0], 14) ^ gmul(a[1], 11) ^ gmul(a[2], 13) ^ gmul(a[3], 9);
        s[i + 1] = gmul(a[0], 9) ^ gmul(a[1], 14) ^ gmul(a[2], 11) ^ gmul(a[3], 13);
        s[i + 2] = gmul(a[0], 13) ^ gmul(a[1], 9) ^ gmul(a[2], 14) ^ gmul(a[3], 11);
        s[i + 3] = gmul(a[0], 11) ^ gmul(a[1], 13) ^ gmul(a[2], 9) ^ gmul(a[3], 14);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(s: &str) -> [u8; 16] {
        let mut out = [0u8; 16];
        for (i, b) in out.iter_mut().enumerate() {
            *b = u8::from_str_radix(&s[2 * i..2 * i + 2], 16).unwrap();
        }
        out
    }

    #[test]
    fn fips_197_encrypt() {
        let key = hex("000102030405060708090a0b0c0d0e0f");
        let mut block = hex("00112233445566778899aabbccddeeff");
        Aes128::new(&key).encrypt_block(&mut block);
        assert_eq!(block, hex("69c4e0d86a7b0430d8cdb78070b4c55a"));
    }

    #[test]
    fn fips_197_decrypt() {
        let key = hex("000102030405060708090a0b0c0d0e0f");
        let mut block = hex("69c4e0d86a7b0430d8cdb78070b4c55a");
        Aes128::new(&key).decrypt_block(&mut block);
        assert_eq!(block, hex("00112233445566778899aabbccddeeff"));
    }

    #[test]
    fn zero_vector() {
        let mut block = [0u8; 16];
        Aes128::new(&[0u8; 16]).encrypt_block(&mut block);
        assert_eq!(block, hex("66e94bd4ef8a2c3b884cfa59ca342b2e"));
    }
}
